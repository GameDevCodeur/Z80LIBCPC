
; ===============================================================
; SCENE MENU - Initialisation
; ===============================================================

F_SCENE_MENU_INITIALISATION

    ; Eteindre écran
    mCRTC_SCREEN_OFF (VOID)

    ; Afficher IMAGE MENU
    LD   HL, MENU_ZX0_DATA
    LD   DE, MENU_LOGO_VRAM
    CALL F_ZX0_DECOMPRESS

    ; Afficher "PRESS KEY TO START"
    mAFFICHER_BLOCK_CHAR_M0 CHAR_P, MENU_TEXT_VRAM
    mAFFICHER_BLOCK_CHAR_M0 CHAR_R, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*1
    mAFFICHER_BLOCK_CHAR_M0 CHAR_E, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*2
    mAFFICHER_BLOCK_CHAR_M0 CHAR_S, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*3
    mAFFICHER_BLOCK_CHAR_M0 CHAR_S, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*4
    mAFFICHER_BLOCK_CHAR_M0 CHAR_K, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*6
    mAFFICHER_BLOCK_CHAR_M0 CHAR_E, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*7
    mAFFICHER_BLOCK_CHAR_M0 CHAR_Y, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*8
    mAFFICHER_BLOCK_CHAR_M0 CHAR_T, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*10
    mAFFICHER_BLOCK_CHAR_M0 CHAR_O, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*11
    mAFFICHER_BLOCK_CHAR_M0 CHAR_S, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*13
    mAFFICHER_BLOCK_CHAR_M0 CHAR_T, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*14
    mAFFICHER_BLOCK_CHAR_M0 CHAR_A, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*15
    mAFFICHER_BLOCK_CHAR_M0 CHAR_R, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*16
    mAFFICHER_BLOCK_CHAR_M0 CHAR_T, MENU_TEXT_VRAM+SCR_PX_PER_BYTE_M0*17

   ;  CHARGE LA PALETTE
   LD   HL, MENU_PAL_DATA
   LD   BC, GA_PORT_CMD 
   LD    A, MENU_PALETTE_SIZE
   mGA_SET_PALETTE (VOID)

   ; Allumer écran
   mCRTC_SCREEN_ON (VOID)

RET    

; ===============================================================
; SCENE MENU - Boucle principale
; ===============================================================

F_SCENE_MENU

   ; Clignotement "PRESS KEY TO START"
   LD   HL, MENU_FLASH_ENTITY
   CALL F_FLASH_ENTITY
   
   ; Test si touche espace pressée
   mKEY_IS_PRESSED_BIT KEY_SPACE : RET NZ

   ; Eteindre écran
   mCRTC_SCREEN_OFF (VOID)

RET
